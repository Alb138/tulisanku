"""Turn 64x64 glyph images into a TrueType font (.ttf).

For every character:
  1. Upscale  the image 4x with smooth (cubic) interpolation and blur it slightly, so the
              traced outline is round instead of following the pixel staircase.
  2. Trace    the line where ink = 0.5 (marching squares, via contourpy): closed polygons
              for the outside of every stroke and the inside of holes (o, e, 8 ...).
  3. Clean    drop tiny specks; simplify every polygon (Ramer-Douglas-Peucker), keeping
              it within a fraction of a pixel of the trace.
  4. Smooth   use the polygon points as TrueType off-curve points: the font renderer then
              draws a smooth quadratic B-spline through them.
  5. Place    convert pixels to font units with the dataset layout (baseline at row 43,
              cap height 36 px = 700 units), add side bearings, and orient outer contours
              clockwise and holes counter-clockwise (the TrueType rule for ink vs. hole).
The model only knows 0-9, A-Z, a-z, so a few punctuation marks (. , : ; - ') are drawn as
simple pen shapes with the writer's measured stroke width.

Licence: the model learned from Google Fonts released under the SIL Open Font License.
Per the OFL FAQ, fonts generated by such a model are derivative works, so every generated
font is released under the OFL 1.1 too (written into the font's name table).
"""
from pathlib import Path

import contourpy
import numpy as np
from fontTools.agl import UV2AGL
from fontTools.fontBuilder import FontBuilder
from fontTools.pens.ttGlyphPen import TTGlyphPen
from matplotlib.path import Path as Polygon
from scipy.ndimage import gaussian_filter, zoom

from .charset import CHARSET
from .nist import BASELINE_ROW, CAP_HEIGHT, X_HEIGHT_LETTERS

UPM = 1000                     # font units per em
UNITS_PER_PX = 700 / CAP_HEIGHT
ZOOM, BLUR = 4, 1.0            # upscaling factor; blur in upscaled pixels
TOLERANCE_PX = 0.15            # simplification error allowed, in 64-px image pixels
MIN_AREA_PX = 1.5              # outlines smaller than this (in px^2) are specks
SIDE_BEARING, SPACE_WIDTH = 50, 280
PUNCTUATION = ".,:;-'"
OFL = ("This Font Software is licensed under the SIL Open Font License, Version 1.1. "
       "This license is available with a FAQ at: https://openfontlicense.org")


def _area(poly: np.ndarray) -> float:
    """Signed area (shoelace); positive = counter-clockwise when y points up."""
    x, y = poly[:, 0], poly[:, 1]
    return 0.5 * float(np.dot(x, np.roll(y, -1)) - np.dot(np.roll(x, -1), y))


def _rdp(points: np.ndarray, tolerance: float) -> np.ndarray:
    """Ramer-Douglas-Peucker: the fewest points that stay within `tolerance` of the line."""
    if len(points) < 3:
        return points
    start, d = points[0], points[-1] - points[0]
    rel = points - start
    norm = np.hypot(*d)
    dist = np.abs(d[0] * rel[:, 1] - d[1] * rel[:, 0]) / norm if norm > 0 else np.hypot(rel[:, 0], rel[:, 1])
    i = int(np.argmax(dist))
    if dist[i] <= tolerance:
        return points[[0, -1]]
    return np.concatenate([_rdp(points[:i + 1], tolerance)[:-1], _rdp(points[i:], tolerance)])


def _simplify_closed(poly: np.ndarray, tolerance: float) -> np.ndarray:
    """RDP for a closed polygon: split it at the point farthest from the first one."""
    far = int(np.argmax(np.hypot(*(poly - poly[0]).T)))
    return np.concatenate([_rdp(poly[:far + 1], tolerance)[:-1], _rdp(np.vstack([poly[far:], poly[:1]]), tolerance)[:-1]])


def trace(image: np.ndarray) -> list:
    """Outline polygons of one glyph image (64x64, ink 0..1) in font units (x right, y up,
    baseline at y = 0), simplified but not yet oriented."""
    big = np.pad(gaussian_filter(zoom(np.asarray(image, np.float64), ZOOM, order=3), BLUR), 1)  # pad: close at borders
    scale = (image.shape[0] - 1) / (big.shape[0] - 3)  # zoom maps the corner pixels onto each other
    polys = []
    for line in contourpy.contour_generator(z=big, line_type=contourpy.LineType.Separate).lines(0.5):
        xy = (line[:-1] - 1) * scale                          # upscaled -> 64-px image coordinates
        if len(xy) < 3 or abs(_area(xy)) < MIN_AREA_PX:
            continue
        xy = _simplify_closed(xy, TOLERANCE_PX)
        if len(xy) >= 3:
            polys.append(np.column_stack([xy[:, 0], BASELINE_ROW - xy[:, 1]]) * UNITS_PER_PX)
    return polys


def orient(polys: list) -> list:
    """Outer contours clockwise, holes counter-clockwise: a contour inside an odd number of
    other contours is a hole."""
    out = []
    for i, p in enumerate(polys):
        depth = sum(Polygon(q).contains_point(p[0]) for j, q in enumerate(polys) if j != i)
        clockwise = depth % 2 == 0
        out.append(p[::-1] if (_area(p) < 0) != clockwise else p)
    return out


def _capsule(p0, p1, width: float, n: int = 8) -> np.ndarray:
    """A pen stroke from p0 to p1 with a round pen: two half circles joined by straight sides."""
    p0, p1 = np.asarray(p0, float), np.asarray(p1, float)
    angle = np.arctan2(*(p1 - p0)[::-1])
    a0 = angle + np.pi / 2 + np.linspace(0, np.pi, n)   # half circle around p0 (the far side)
    a1 = angle - np.pi / 2 + np.linspace(0, np.pi, n)   # half circle around p1
    r = width / 2
    return np.vstack([p0 + r * np.column_stack([np.cos(a0), np.sin(a0)]),
                      p1 + r * np.column_stack([np.cos(a1), np.sin(a1)])])


def stroke_width(polys_per_glyph: list) -> float:
    """Typical pen width from oriented outlines: a thin stroke has area ~ length * width and
    perimeter ~ 2 * length."""
    area = -sum(_area(p) for polys in polys_per_glyph for p in polys)  # ink is clockwise = negative area
    perimeter = sum(np.hypot(*np.diff(np.vstack([p, p[:1]]), axis=0).T).sum() for polys in polys_per_glyph for p in polys)
    return float(np.clip(2 * area / max(perimeter, 1), 25, 200))


def punctuation(width: float, x_height: float) -> dict:
    """Simple pen-drawn punctuation in font units (origin on the baseline)."""
    dot = _capsule((0, width * 0.6), (0, width * 0.6 + 1), width * 1.2)
    comma = _capsule((width * 0.2, width * 0.6), (-width * 0.4, -width * 2.2), width * 1.1)
    high = (0, x_height * 0.85)
    return {".": [dot], ",": [comma], ":": [dot, dot + high], ";": [comma, dot + high],
            "-": [_capsule((0, x_height * 0.5), (x_height * 0.6, x_height * 0.5), width)],
            "'": [_capsule((0, 700), (-width * 0.2, 700 - width * 2.5), width * 1.1)]}


def _glyph(polys: list):
    """Draw oriented polygons as all-off-curve quadratic contours; returns (glyph, advance width)."""
    pen = TTGlyphPen(None)
    x_min = min(p[:, 0].min() for p in polys)
    shift = SIDE_BEARING - x_min
    for p in polys:
        pts = np.round(p + [shift, 0]).astype(int)
        pts = pts[np.any(pts != np.roll(pts, 1, axis=0), axis=1)]  # rounding can create duplicate points
        if len(pts) >= 3:
            pen.qCurveTo(*map(tuple, pts.tolist()), None)
            pen.closePath()
    width = max(p[:, 0].max() for p in polys) - x_min
    return pen.glyph(), int(round(width + 2 * SIDE_BEARING))


def _notdef():
    pen = TTGlyphPen(None)
    for box in ([(50, 0), (50, 700), (450, 700), (450, 0)], [(100, 50), (400, 50), (400, 650), (100, 650)]):
        pen.moveTo(box[0])
        for pt in box[1:]:
            pen.lineTo(pt)
        pen.closePath()
    return pen.glyph()


def build_font(images: np.ndarray, path: Path, family: str, chars: str = CHARSET) -> Path:
    """images [len(chars), 64, 64] with ink 0..1 -> a TrueType font saved at `path`."""
    outlines = {ch: orient(trace(img)) for ch, img in zip(chars, images)}
    drawn = [polys for polys in outlines.values() if polys]
    xh = [max(p[:, 1].max() for p in outlines[c]) for c in X_HEIGHT_LETTERS if outlines.get(c)]
    x_height = float(np.median(xh)) if xh else 420.0
    outlines.update({ch: orient(polys) for ch, polys in punctuation(stroke_width(drawn), x_height).items()})

    names = {ch: UV2AGL[ord(ch)] for ch in outlines}
    order = [".notdef", "space", *names.values()]
    glyphs, advances = {".notdef": _notdef(), "space": TTGlyphPen(None).glyph()}, {".notdef": 500, "space": SPACE_WIDTH}
    for ch, polys in outlines.items():
        if polys:
            glyphs[names[ch]], advances[names[ch]] = _glyph(polys)
        else:  # nothing traced (blank image): keep the character typable as a blank
            glyphs[names[ch]], advances[names[ch]] = TTGlyphPen(None).glyph(), SPACE_WIDTH

    fb = FontBuilder(UPM, isTTF=True)
    fb.setupGlyphOrder(order)
    fb.setupCharacterMap({32: "space", **{ord(ch): names[ch] for ch in outlines}})
    fb.setupGlyf(glyphs)
    glyf = fb.font["glyf"]
    fb.setupHorizontalMetrics({g: (advances[g], getattr(glyf[g], "xMin", 0)) for g in order})
    y_max = max(getattr(glyf[g], "yMax", 0) for g in order)
    y_min = min(getattr(glyf[g], "yMin", 0) for g in order)
    ascent, descent = int(BASELINE_ROW * UNITS_PER_PX), -int((64 - BASELINE_ROW) * UNITS_PER_PX)
    fb.setupHorizontalHeader(ascent=ascent, descent=descent)
    ps_name = "".join(c for c in family if c.isalnum()) + "-Regular"
    fb.setupNameTable({"familyName": family, "styleName": "Regular", "fullName": f"{family} Regular",
                       "psName": ps_name, "uniqueFontIdentifier": f"TULISANKU: {ps_name}", "version": "Version 1.000",
                       "description": "Generated by TULISANKU from a few handwritten letters; "
                                      "a derivative of fonts under the SIL Open Font License.",
                       "licenseDescription": OFL, "licenseInfoURL": "https://openfontlicense.org"})
    fb.setupOS2(sTypoAscender=ascent, sTypoDescender=descent, sTypoLineGap=0,
                usWinAscent=max(ascent, y_max), usWinDescent=max(-descent, -y_min),
                sxHeight=int(x_height), sCapHeight=700, fsType=0)
    fb.font["OS/2"].recalcUnicodeRanges(fb.font)
    fb.setupPost()
    path = Path(path)
    path.parent.mkdir(parents=True, exist_ok=True)
    fb.save(path)
    return path
